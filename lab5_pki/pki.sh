#!/usr/bin/env bash
# =============================================================================
# Laboratory Work No. 5 — Public Key Infrastructure (PKI) and Digital Signatures
# Internal PKI built with the OpenSSL command-line tool.
#
#   CA      : RSA 4096-bit root key, self-signed certificate valid 3650 days
#   Users   : RSA 2048-bit keys, certificates issued by the CA, valid 365 days
#   Actions : issue / revoke user keys+certificates, publish CRL,
#             sign files, verify signatures (signature + certificate chain + CRL)
#
# Author : Strunga Daniel-Ioan, FAF-242
# Repo   : https://github.com/don09dandidi/CS
#
# Usage:
#   ./pki.sh init-ca                      create the Certification Authority
#   ./pki.sh issue  <user> [user-bits]    generate key + CSR, CA issues certificate
#   ./pki.sh sign   <user> <file>         create <file>.<user>.sig (RSA + SHA-256)
#   ./pki.sh verify <user> <file> [sig]   verify certificate (chain + CRL) and signature
#   ./pki.sh revoke <user> [reason]       revoke the user's certificate, update the CRL
#   ./pki.sh list                         show the CA database (index.txt)
#   ./pki.sh info   <user>                show the user's certificate
#   ./pki.sh demo                         run the complete scenario
#
# The PKI lives in $PKI_DIR (default: ./pki). Works with OpenSSL 1.1/3.x and LibreSSL.
# =============================================================================
set -euo pipefail

PKI_DIR="${PKI_DIR:-$(pwd)/pki}"
CA_DIR="$PKI_DIR/ca"
USERS_DIR="$PKI_DIR/users"
CA_KEY_BITS=4096
CA_DAYS=3650
USER_KEY_BITS=2048
USER_DAYS=365
DIGEST=sha256
CA_SUBJ="/C=MD/ST=Chisinau/L=Chisinau/O=UTM FCIM/OU=FAF-242/CN=FAF-242 Root CA"

if [[ -t 1 ]]; then B=$'\033[1;34m' G=$'\033[1;32m' R=$'\033[1;31m' N=$'\033[0m'; else B= G= R= N=; fi
c_info()  { printf '%s[*]%s %s\n' "$B" "$N" "$*"; }
c_ok()    { printf '%s[OK]%s %s\n' "$G" "$N" "$*"; }
c_err()   { printf '%s[FAIL]%s %s\n' "$R" "$N" "$*" >&2; }
die()     { c_err "$*"; exit 1; }
need_ca() { [[ -f "$CA_DIR/certs/ca.crt" ]] || die "CA not initialised — run: $0 init-ca"; }
valid_name() { [[ "$1" =~ ^[A-Za-z0-9._-]+$ ]] || die "invalid user name '$1' (allowed: A-Z a-z 0-9 . _ -)"; }

write_config() {
cat > "$CA_DIR/openssl.cnf" <<EOF
# OpenSSL configuration of the FAF-242 internal CA (generated by pki.sh)
[ ca ]
default_ca        = CA_default

[ CA_default ]
dir               = $CA_DIR
certs             = \$dir/certs
crl_dir           = \$dir/crl
new_certs_dir     = \$dir/newcerts
database          = \$dir/index.txt
serial            = \$dir/serial
crlnumber         = \$dir/crlnumber
private_key       = \$dir/private/ca.key
certificate       = \$dir/certs/ca.crt
crl               = \$dir/crl/ca.crl.pem
default_md        = $DIGEST
default_days      = $USER_DAYS
default_crl_days  = 30
preserve          = no
policy            = policy_user
unique_subject    = no
copy_extensions   = none

[ policy_user ]
countryName             = optional
stateOrProvinceName     = optional
localityName            = optional
organizationName        = match
organizationalUnitName  = optional
commonName              = supplied
emailAddress            = optional

[ req ]
default_bits        = $USER_KEY_BITS
distinguished_name  = req_dn
string_mask         = utf8only
default_md          = $DIGEST
prompt              = no

[ req_dn ]
CN = placeholder

[ v3_ca ]
subjectKeyIdentifier   = hash
authorityKeyIdentifier = keyid:always,issuer
basicConstraints       = critical, CA:true
keyUsage               = critical, digitalSignature, cRLSign, keyCertSign

[ usr_sign ]
basicConstraints       = critical, CA:false
subjectKeyIdentifier   = hash
authorityKeyIdentifier = keyid,issuer
keyUsage               = critical, digitalSignature, nonRepudiation
extendedKeyUsage       = codeSigning, emailProtection
crlDistributionPoints  = URI:file://$CA_DIR/crl/ca.crl.pem

[ crl_ext ]
authorityKeyIdentifier = keyid:always
EOF
}

gen_crl() {
    openssl ca -config "$CA_DIR/openssl.cnf" -gencrl -out "$CA_DIR/crl/ca.crl.pem" 2>/dev/null
}

cmd_init_ca() {
    [[ -f "$CA_DIR/certs/ca.crt" ]] && die "CA already exists in $CA_DIR (remove $PKI_DIR to start over)"
    c_info "Creating directory structure in $CA_DIR"
    mkdir -p "$CA_DIR"/{certs,crl,newcerts,private} "$USERS_DIR"
    chmod 700 "$CA_DIR/private"
    : > "$CA_DIR/index.txt"
    echo 1000 > "$CA_DIR/serial"
    echo 1000 > "$CA_DIR/crlnumber"
    write_config

    c_info "Generating the CA root private key (RSA $CA_KEY_BITS bits)"
    openssl genrsa -out "$CA_DIR/private/ca.key" "$CA_KEY_BITS" 2>/dev/null
    chmod 600 "$CA_DIR/private/ca.key"

    c_info "Creating the self-signed CA certificate (valid $CA_DAYS days)"
    openssl req -config "$CA_DIR/openssl.cnf" -new -x509 -days "$CA_DAYS" -$DIGEST \
        -key "$CA_DIR/private/ca.key" -subj "$CA_SUBJ" -extensions v3_ca \
        -out "$CA_DIR/certs/ca.crt"

    gen_crl
    c_ok "CA initialised"
    openssl x509 -in "$CA_DIR/certs/ca.crt" -noout -subject -issuer -dates -serial
}

cmd_issue() {
    need_ca
    local user="${1:?usage: $0 issue <user> [bits]}" bits="${2:-$USER_KEY_BITS}"
    valid_name "$user"
    (( bits >= 2048 )) || die "user keys must be at least 2048 bits"
    local d="$USERS_DIR/$user"
    if grep -q "^V.*/CN=$user\$" "$CA_DIR/index.txt"; then
        die "user '$user' already has a valid certificate (revoke it first)"
    fi
    mkdir -p "$d"
    c_info "Generating private key for '$user' (RSA $bits bits)"
    openssl genrsa -out "$d/$user.key" "$bits" 2>/dev/null
    chmod 600 "$d/$user.key"

    c_info "Creating the certificate signing request (CSR)"
    openssl req -config "$CA_DIR/openssl.cnf" -new -key "$d/$user.key" -$DIGEST \
        -subj "/C=MD/L=Chisinau/O=UTM FCIM/OU=FAF-242/CN=$user" -out "$d/$user.csr"

    c_info "CA signs the CSR -> certificate valid $USER_DAYS days"
    openssl ca -config "$CA_DIR/openssl.cnf" -batch -notext -extensions usr_sign \
        -days "$USER_DAYS" -in "$d/$user.csr" -out "$d/$user.crt" 2>/dev/null
    cp "$CA_DIR/certs/ca.crt" "$d/ca.crt"
    openssl x509 -in "$d/$user.crt" -pubkey -noout > "$d/$user.pub.pem"
    c_ok "Issued certificate for '$user'"
    openssl x509 -in "$d/$user.crt" -noout -subject -issuer -dates -serial
}

cmd_sign() {
    need_ca
    local user="${1:?usage: $0 sign <user> <file>}" file="${2:?usage: $0 sign <user> <file>}"
    valid_name "$user"
    local d="$USERS_DIR/$user"
    [[ -f "$d/$user.key" ]] || die "no private key for '$user'"
    [[ -f "$file" ]] || die "file not found: $file"
    if ! openssl verify -crl_check -CAfile "$CA_DIR/certs/ca.crt" \
            -CRLfile "$CA_DIR/crl/ca.crl.pem" "$d/$user.crt" >/dev/null 2>&1; then
        die "certificate of '$user' is revoked or invalid — signing refused"
    fi
    local sig="$file.$user.sig"
    openssl dgst -$DIGEST -sign "$d/$user.key" -out "$sig" "$file"
    c_ok "'$user' signed $file -> $sig ($(wc -c < "$sig" | tr -d ' ') bytes, RSA/$DIGEST)"
    printf '     %s(file) = %s\n' "$DIGEST" "$(openssl dgst -$DIGEST -r "$file" | cut -d' ' -f1)"
}

cmd_verify() {
    need_ca
    local user="${1:?usage: $0 verify <user> <file> [sig]}" file="${2:?}"
    valid_name "$user"
    local sig="${3:-$file.$user.sig}" d="$USERS_DIR/$user" status=0
    [[ -f "$file" && -f "$sig" ]] || die "file or signature missing"
    gen_crl
    c_info "1) Certificate chain + revocation check (CA + CRL)"
    if openssl verify -crl_check -CAfile "$CA_DIR/certs/ca.crt" \
            -CRLfile "$CA_DIR/crl/ca.crl.pem" "$d/$user.crt"; then
        c_ok "certificate of '$user' is valid and not revoked"
    else
        c_err "certificate of '$user' is NOT trusted (revoked or invalid)"; status=1
    fi
    c_info "2) Cryptographic signature check with the public key from the certificate"
    openssl x509 -in "$d/$user.crt" -pubkey -noout > "$d/$user.pub.pem"
    if openssl dgst -$DIGEST -verify "$d/$user.pub.pem" -signature "$sig" "$file"; then
        c_ok "signature matches the file"
    else
        c_err "signature does NOT match the file"; status=1
    fi
    if (( status == 0 )); then c_ok "RESULT: signature of '$user' on $file is VALID"
    else c_err "RESULT: signature of '$user' on $file is REJECTED"; fi
    return $status
}

cmd_revoke() {
    need_ca
    local user="${1:?usage: $0 revoke <user> [reason]}" reason="${2:-keyCompromise}"
    valid_name "$user"
    local crt="$USERS_DIR/$user/$user.crt"
    [[ -f "$crt" ]] || die "no certificate for '$user'"
    c_info "Revoking certificate of '$user' (reason: $reason)"
    openssl ca -config "$CA_DIR/openssl.cnf" -revoke "$crt" -crl_reason "$reason" 2>/dev/null
    gen_crl
    c_ok "Certificate revoked, CRL updated: $CA_DIR/crl/ca.crl.pem"
    openssl crl -in "$CA_DIR/crl/ca.crl.pem" -noout -text | grep -E "Serial Number|Revocation Date|Key Compromise|Superseded|Cessation|Unspecified" || true
}

cmd_list() {
    need_ca
    printf '%-6s %-16s %-8s %s\n' "STATUS" "EXPIRES" "SERIAL" "SUBJECT"
    awk -F'\t' '{st=($1=="V")?"valid":($1=="R")?"REVOKED":"expired";
                 printf "%-6s %-16s %-8s %s\n", st, $2, $4, $6}' "$CA_DIR/index.txt"
}

cmd_info() {
    local user="${1:?usage: $0 info <user>}"
    valid_name "$user"
    openssl x509 -in "$USERS_DIR/$user/$user.crt" -noout -text \
        | grep -E "Serial Number|Issuer:|Subject:|Not Before|Not After|Public-Key|Digital Signature|CA:" 
}

cmd_demo() {
    local tmp; tmp="$(mktemp -d)"
    export PKI_DIR="$tmp/pki"
    PKI_DIR="$tmp/pki"; CA_DIR="$PKI_DIR/ca"; USERS_DIR="$PKI_DIR/users"
    local doc="$tmp/contract.txt"
    printf 'Contract nr. 22/2026\nStrunga Daniel-Ioan, FAF-242\n' > "$doc"
    echo "========== 1. Initialise the CA ==========";           cmd_init_ca
    echo; echo "========== 2. Issue keys for alice and bob =========="
    cmd_issue alice; cmd_issue bob
    echo; echo "========== 3. alice signs a document ==========";   cmd_sign alice "$doc"
    echo; echo "========== 4. Verification ==========";             cmd_verify alice "$doc"
    echo; echo "========== 5. Tampered document ==========";
    local fake="$tmp/contract_modified.txt"
    cp "$doc" "$fake"; printf 'Suma: 1000000 MDL\n' >> "$fake"
    cmd_verify alice "$fake" "$doc.alice.sig" || true
    echo; echo "========== 6. Wrong signer (bob's certificate) =========="
    cmd_verify bob "$doc" "$doc.alice.sig" || true
    echo; echo "========== 7. Revoke alice ==========";             cmd_revoke alice keyCompromise
    echo; echo "========== 8. Verification after revocation =========="
    cmd_verify alice "$doc" || true
    echo; echo "========== 9. Revoked user tries to sign =========="
    ( cmd_sign alice "$doc" ) || true
    echo; echo "========== 10. CA database ==========";            cmd_list
    echo; echo "(demo PKI created in $tmp)"
}

case "${1:-}" in
    init-ca) shift; cmd_init_ca "$@" ;;
    issue)   shift; cmd_issue "$@" ;;
    sign)    shift; cmd_sign "$@" ;;
    verify)  shift; cmd_verify "$@" ;;
    revoke)  shift; cmd_revoke "$@" ;;
    list)    shift; cmd_list "$@" ;;
    info)    shift; cmd_info "$@" ;;
    demo)    shift; cmd_demo "$@" ;;
    *) sed -n '2,24p' "$0" | sed 's/^# \{0,1\}//'; exit 1 ;;
esac
